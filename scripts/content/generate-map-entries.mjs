#!/usr/bin/env node
/**
 * 用实体 dump 目录批量生成地图条目（MDX）。
 *
 * 数据来源：public/entity/catalog.json（由 build-entity-data.mjs 生成）
 * 可选增强：data/research/<slug>.json（线上检索到的资料，见下方格式）
 *
 * 规则：
 *   - 只处理 ZE（模式 2001）
 *   - 不覆盖手写条目（没有生成标记的 MDX 一律跳过）
 *   - 自己生成的条目再次运行会整份重写
 *   - 有 research 资料的条目：stub=false，并把摘要/难度/作者等写进 frontmatter 与正文
 *
 * research JSON 格式：
 *   { "slug": "...", "summary": "markdown 文本", "difficulty": "困难",
 *     "author": "...", "players": "32-64", "duration": "40-60 分钟",
 *     "tags": ["..."], "videoUrls": ["..."], "sources": ["https://..."], "verified": true }
 *
 * 用法：
 *   node scripts/content/generate-map-entries.mjs                 # 生成/更新
 *   node scripts/content/generate-map-entries.mjs --priority 60   # 输出待检索地图优先级表
 *   node scripts/content/generate-map-entries.mjs --dry           # 只统计不写文件
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const MAPS_DIR = path.join(ROOT, 'src/content/maps');
const RESEARCH_DIR = path.join(ROOT, 'data/research');
const MARK = 'generated by scripts/content/generate-map-entries.mjs';
const zlib = await import('node:zlib');

const argv = process.argv.slice(2);
const DRY = argv.includes('--dry');
const PRIORITY = argv.includes('--priority') ? Number(argv[argv.indexOf('--priority') + 1] || 40) : 0;

const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/entity/catalog.json'), 'utf8'));
const zeMaps = catalog.maps.filter((m) => m.a === '2001');

/* 手写条目已经覆盖的地图（含各版本），生成时跳过，避免重复条目 */
const LINKS = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/content/curated-links.json'), 'utf8'));
const curatedMaps = new Set();
for (const [slug, info] of Object.entries(LINKS)) {
  if (slug.startsWith('_')) continue;
  for (const v of info.versions || []) curatedMaps.add(v);
}

const n = (v) => v.toLocaleString('en-US');

/* ---------------- 优先级表（给线上检索用） ---------------- */
if (PRIORITY) {
  const curated = new Set(fs.readdirSync(MAPS_DIR).map((f) => f.replace(/\.mdx$/, '')));
  const list = [...zeMaps]
    .sort((a, b) => b.n - a.n)
    .filter((m) => !curated.has(m.m) && !curatedMaps.has(m.m))
    .slice(0, PRIORITY)
    .map((m, i) => ({
      rank: i + 1,
      slug: m.s,
      slugOut: m.m,
      map: m.m,
      cn: m.cn,
      workshopId: m.f,
      entities: n(m.n),
      stages: m.st,
      published: m.d,
      top: (m.t || []).slice(0, 3).map((x) => x[0]),
    }));
  fs.mkdirSync(RESEARCH_DIR, { recursive: true });
  const out = path.join(RESEARCH_DIR, 'priority.json');
  fs.writeFileSync(out, JSON.stringify(list, null, 1));
  console.log(`待检索优先级表 → ${path.relative(ROOT, out)}（${list.length} 张，按实体量排序）`);
  for (const x of list.slice(0, 12)) console.log(`  ${String(x.rank).padStart(2)}. ${x.slugOut}  ${x.cn}  实体 ${x.entities}`);
  process.exit(0);
}

/* ---------------- 自动标签（有阈值，避免所有图都挂同一批标签） ---------------- */
/** 标签会变成 /tags/<tag>/ 路径：去掉文件系统与 URL 里的危险字符 */
const safeTag = (t) =>
  String(t || '')
    .replace(/[\\/:*?"<>|#%]/g, '·')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 24);

/* 标签大小写归一：
 * 同一个标签出现 Boss / boss / BOSS 三种写法时，Windows 上会写进同一个目录，
 * 但 Cloudflare 是大小写敏感的文件系统，另一种写法就会 404。
 * 这里先统计所有来源（手写条目 + 检索资料）的写法，按「手写优先 → 出现次数多优先」
 * 选出一个规范写法，生成时统一使用。 */
const tagVariants = new Map(); // lower -> Map(写法 -> {count, curated})
const noteTag = (tag, curated) => {
  const t = safeTag(tag);
  if (!t) return;
  const key = t.toLowerCase();
  if (!tagVariants.has(key)) tagVariants.set(key, new Map());
  const variants = tagVariants.get(key);
  const cur = variants.get(t) || { count: 0, curated: false };
  cur.count++;
  if (curated) cur.curated = true;
  variants.set(t, cur);
};
const canonTag = (tag) => {
  const t = safeTag(tag);
  if (!t) return t;
  const variants = tagVariants.get(t.toLowerCase());
  if (!variants) return t;
  // 平票时优先选「不是全大写前缀」的写法（Boss战 优于 BOSS战）
  const shape = (s) => (/^[A-Z0-9]{2,}/.test(s) ? 0 : 1);
  const list = [...variants.entries()];
  list.sort(
    (a, b) =>
      Number(b[1].curated) - Number(a[1].curated) ||
      b[1].count - a[1].count ||
      shape(b[0]) - shape(a[0])
  );
  return list[0][0];
};

function autoTags(rec) {
  const c = rec.c || {};
  const t = [];
  if ((c.mech || 0) >= 150) t.push('机关图');
  if ((c.break || 0) >= 100) t.push('可破坏物');
  if ((c.tele || 0) >= 80) t.push('传送门多');
  if ((c.hurt || 0) >= 30) t.push('危险区多');
  if ((c.path || 0) >= 150) t.push('路径多');
  if ((rec.st || 0) >= 6) t.push('多关卡');
  if ((rec.n || 0) >= 2000) t.push('大图');
  if (rec.rb) t.push('有雷达图');
  return t;
}

