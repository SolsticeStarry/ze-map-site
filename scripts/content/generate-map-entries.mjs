/* GFL 公开服务器配置解析结果（scripts/content/parse-gfl-configs.mjs 产出）
   别名表 _aliases.json 由 link-gfl-configs.mjs 生成：只允许「同名」或「仅差移植/版本后缀」
   的映射，避免把别的图的神器表安到这张图上。 */
const GFL_DIR = path.join(ROOT, 'data/gfl-parsed');
const gflAliases = fs.existsSync(path.join(GFL_DIR, '_aliases.json'))
  ? readJson(path.join(GFL_DIR, '_aliases.json'))
  : {};
function loadGfl(mapName) {
  const target = gflAliases[mapName] || mapName;
  const f = path.join(GFL_DIR, `${target}.json`);
  if (!fs.existsSync(f)) return null;
  try {
    const data = readJson(f);
    return { ...data, _from: target === mapName ? null : target };
  } catch { return null; }
}

/* 关卡数复核：dump 的 st 字段偶尔偏低（例：ze_minecraft_universe 记为 1，
   但实体里有 stage1_exit / 31 个 stage2_* 实体，GFL 也登记了 stage2 的 BOSS）。
   这里只在实体名**明确**写了 stageN / lvlN 时才修正，且要求编号基本连续，
   避免把楼层号、偶发命名当成关卡号（例如 [1,10] 这种会被拒绝）。 */
const STAGE_NAME_RE = /(?:^|[^a-z])(?:stage|lvl|level)[\s_-]?(\d{1,2})(?![0-9])/gi;
function stageCountFromEntities(slug, dumpStages) {
  const f = path.join(ROOT, 'public/entity/data', `${slug}.bin`);
  if (!fs.existsSync(f)) return { stages: dumpStages, from: null };
  try {
    const raw = zlib.gunzipSync(fs.readFileSync(f));
    const jlen = raw.readUInt32LE(0);
    const payload = JSON.parse(raw.subarray(4, 4 + jlen).toString('utf8'));
    const nums = new Set();
    let refs = 0;
    for (const e of payload.map.e) {
      if (typeof e[4] !== 'string' || !e[4]) continue;
      let hit = false;
      for (const m of e[4].matchAll(STAGE_NAME_RE)) { nums.add(Number(m[1])); hit = true; }
      if (hit) refs++;
    }
    const maxN = nums.size ? Math.max(...nums) : 0;
    const coverage = maxN ? [...nums].filter((n) => n >= 1 && n <= maxN).length / maxN : 0;
    if (maxN > dumpStages && nums.size >= 2 && refs >= 10 && maxN <= 12 && coverage >= 0.6) {
      return { stages: maxN, from: `实体命名 [${[...nums].sort((a, b) => a - b).join(',')}]` };
    }
  } catch { /* 分片读不了就用原值 */ }
  return { stages: dumpStages, from: null };
}
const excerpt = (s, max = 420) => {
  const t = String(s || '').replace(/\s*\n\s*/g, '\n').trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const stop = Math.max(cut.lastIndexOf('\n'), cut.lastIndexOf('。'), cut.lastIndexOf('. '));
  return (stop > max * 0.5 ? cut.slice(0, stop) : cut).trim() + ' …';
};

/** MDX 是 JSX 语法：正文里的 < 和 { 会被当成标签/表达式，必须转义 */
const mdSafe = (s) => String(s || '').replace(/</g, '&lt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;');

/* ---------------- 生成一个条目的 MDX ---------------- */
function renderEntry(rec, research, wsRec, gfl) {
  const slug = rec.m;
  const wsUrl = `https://steamcommunity.com/sharedfiles/filedetails/?id=${rec.f}`;
  const groups = Object.fromEntries((catalog.groups || []).map((g) => [g.id, g]));
  const cats = Object.entries(rec.c || {}).sort((a, b) => b[1] - a[1]);
  const subs = wsRec?.result === 1 ? (wsRec.subscriptions ?? 0) : 0;
  const tags = [
    ...new Set(
      [
        ...autoTags(rec),
        ...(subs >= 5000 ? ['热门'] : []),
        ...(wsRec && wsRec.result !== 1 ? ['已下架'] : []),
        ...(research?.tags || []),
      ]
        .map(safeTag)
        .map(canonTag)
        .filter(Boolean)
    ),
  ];
  const diff = ['简单', '中等', '困难', '极难', '地狱'].includes(research?.difficulty) ? research.difficulty : '未知';
  // 发布日期优先用工坊 API 的权威时间
  const released = wsRec?.timeCreated || rec.d;
  const updated = wsRec?.timeUpdated || rec.d || catalog.meta.built.slice(0, 10);
  const desc = wsRec?.result === 1 ? (wsRec.description || '').trim() : '';
  const hasEditorial = Boolean(research?.summary);
  // 卡片封面：由实体数据渲染的 16:9 缩略图（render-covers.mjs）
  const coverRel = `/images/covers/${rec.s}.webp`;
  const hasCover = fs.existsSync(path.join(ROOT, 'public', coverRel));
  // 上传者昵称：仅在正文说明里用，不冒充「作者」（很多是 CS2 移植上传者）
  const uploader = wsRec?.result === 1 ? uploaderOf(wsRec.creator) : '';
  // 作者署名可能很长（多作者 / 原作与移植的区分）：侧栏只显示第一段，完整署名放 authorNote
  const rawAuthor = (research?.author || '').trim();
  const authorShort = rawAuthor.includes('；') ? rawAuthor.split('；')[0].trim() : rawAuthor;
  const authorNote = rawAuthor && authorShort !== rawAuthor ? rawAuthor : '';

  const fm = [
    '---',
    `title: ${JSON.stringify((research?.title || rec.cn || rec.m).trim())}`,
    `titleEn: ${JSON.stringify(rec.m)}`,
    `game: CS2`,
    research?.author ? `author: ${JSON.stringify(authorShort)}` : null,
    authorNote ? `authorNote: ${JSON.stringify(authorNote)}` : null,
    `difficulty: ${diff}`,
    research?.players ? `players: ${JSON.stringify(research.players)}` : null,
    research?.duration ? `duration: ${JSON.stringify(research.duration)}` : null,
    `stages: ${rec.st || 0}`,
    `tags: [${tags.map((x) => JSON.stringify(x)).join(', ')}]`,
    hasCover ? `cover: ${JSON.stringify(coverRel)}` : null,
    `workshopUrl: ${wsUrl}`,
    `workshopId: ${JSON.stringify(rec.f)}`,
    subs ? `workshopSubs: ${subs}` : null,
    wsRec?.views ? `workshopViews: ${wsRec.views}` : null,
    uploader && !research?.author ? `uploader: ${JSON.stringify(uploader)}` : null,
    wsRec && wsRec.result !== 1 ? `workshopMissing: true` : null,
    `entitySlug: ${JSON.stringify(rec.s)}`,
    `entityKey: ${JSON.stringify(rec.k)}`,
    `entityCount: ${rec.n}`,
    released ? `releaseDate: ${JSON.stringify(released)}` : null,
    `lastUpdated: ${JSON.stringify(updated)}`,
    research?.videoUrls?.length ? `videoUrls: [${research.videoUrls.map((x) => JSON.stringify(x)).join(', ')}]` : null,
    research?.sources?.length ? `sources: [${research.sources.map((x) => JSON.stringify(x)).join(', ')}]` : null,
    `stub: ${hasEditorial ? 'false' : 'true'}`,
    '---',
    '',
    `{/* ${MARK} · 实体数据：${catalog.meta.source} · 快照 ${catalog.meta.built} · 工坊数据：Steam Web API */}`,
    '',
  ].filter(Boolean);

  const body = [];

  if (hasEditorial) {
    body.push(mdSafe(research.summary.trim()), '');
  }
  // 数据条目的「资料待补充」提示由详情页统一渲染（stub 字段），正文里不再重复

  if (desc) {
    body.push(
      '## 工坊页面自述',
      '',
      '> ' + mdSafe(excerpt(desc)).split('\n').filter(Boolean).join('\n> '),
      '',
      `> 以上为作者在工坊页面的原文摘录，完整内容见 [Steam 创意工坊](${wsUrl})。`,
      ''
    );
  } else if (wsRec && wsRec.result !== 1) {
    body.push(
      '> 该地图的工坊条目在 Steam 上已**查无此项**（可能是作者删除或设为隐藏），下方实体数据仍来自服务器端记录。',
      ''
    );
  }

  body.push(
    '## 数据概况',
    '',
    '| 项目 | 内容 |',
    '|---|---|',
    `| 地图英文名 | ${rec.m} |`,
    `| 工坊文件 ID | [${rec.f}](${wsUrl}) |`,
    uploader ? `| 工坊上传者 | ${uploader} |` : null,
    `| 适用游戏 | CS2 |`,
    released ? `| 工坊发布 | ${released} |` : null,
    wsRec?.timeUpdated ? `| 工坊最近更新 | ${wsRec.timeUpdated} |` : null,
    subs ? `| 工坊订阅数 | ${n(subs)} |` : null,
    wsRec?.views ? `| 工坊浏览量 | ${n(wsRec.views)} |` : null,
    `| 实体总数 | ${n(rec.n)} |`,
    `| 可绘制点位 | ${n(rec.k2)} |`,
    `| 关卡数 | ${rec.st || 0}${rec.st ? '（按实体命名推断）' : ''} |`,
    ''
  );

  body.push(
    '## 实体构成',
    '',
    `本图共记录 ${n(rec.n)} 个实体，其中 ${n(rec.k2)} 个是可绘制的玩法点位：`,
    '',
    '| 类别 | 数量 |',
    '|---|---|',
    ...cats.map(([gid, cnt]) => `| ${groups[gid]?.label || gid} | ${n(cnt)} |`),
    '',
    (rec.t || []).length
      ? `数量最多的实体类型：${rec.t.slice(0, 6).map((x) => `\`${x[0]}\` ${n(x[1])}`).join(' · ')}。`
      : null,
    ''
  );

  if (rec.st) {
    body.push(
      '## 关卡',
      '',
      `按实体命名（\`lvl2\` / \`stage3\` 之类）推断，本图共 **${rec.st}** 个关卡。`,
      '在实体预览里可以按关卡分层查看，切换关卡时镜头会自动飞到该关范围。',
      ''
    );
  }

  if (gfl?.items?.length) {
    body.push(
      '## 神器 / 道具（服务器配置）',
      '',
      `以下 ${gfl.items.length} 件道具来自公开的服务器 entwatch 配置，是本图在服务器上实际注册的神器与道具${gfl._from ? `（取自 GFL 的 \`${gfl._from}\` 配置）` : ''}：`,
      '',
      '| 道具 | 冷却 | 使用次数 |',
      '|---|---|---|',
      ...gfl.items.map((it) => {
        const uses = it.maxuses ? `${it.maxuses} 次` : '不限';
        const cd = it.cd ? `${it.cd} 秒` : '—';
        return `| ${mdSafe(it.name)} | ${cd} | ${uses} |`;
      }),
      ''
    );
  }

  if (gfl?.bosses?.length) {
    body.push(
      '## BOSS',
      '',
      `服务器 bosshud 配置登记了 ${gfl.bosses.length} 个 BOSS：${gfl.bosses.map((b) => mdSafe(b)).join(' · ')}。`,
      ''
    );
  }

  if (gfl?.music?.length) {
    const shown = gfl.music.slice(0, 12);
    body.push(
      '## 音乐',
      '',
      `本图在服务器上登记了 ${gfl.music.length} 首 BGM，例如：`,
      '',
      ...shown.map((t) => `- ${mdSafe(t)}`),
      gfl.music.length > shown.length ? `- …等共 ${gfl.music.length} 首` : null,
      ''
    );
  }

  body.push(
    '## 实体预览',
    '',
    `[打开《${rec.cn || rec.m}》的实体预览 →](/preview/?map=${rec.s})`,
    '',
    '可交互查看本图的可破坏物、传送门、机关、危险区、路径点等点位，支持 3D / 平面两种视图与关卡分层。',
    ''
  );

  if (research?.sources?.length) {
    body.push('## 资料来源', '', ...research.sources.map((s) => `- ${s}`), '');
  }

  body.push(
    '## 数据说明',
    '',
    `- 实体数据来自 CS2 服务端实体 dump（${catalog.meta.source}），快照时间 ${catalog.meta.built}。`,
    `- ${catalog.meta.note || ''}`,
    `- ${catalog.meta.vol_note || ''}`,
    gfl ? '- 神器 / 道具、BOSS 与音乐名单来自 GFL 公开服务器配置（entwatch / bosshud / musicname），可能与其它服务器不一致。' : null,
    '- 关卡数由实体命名（lvl2 / stage3 等）推断，未命名的按就近标注推断，可能与服务器配置或实际流程略有出入。',
    ''
  );

  return fm.join('\n') + '\n' + body.filter((x) => x !== null).join('\n');
}

/* ---------------- 主流程 ---------------- */
fs.mkdirSync(RESEARCH_DIR, { recursive: true });
const researchFiles = new Map();
/** 资料可能以「地图内部名」或「数据分片名(2001-ze_xxx-123456)」作为 slug，两种都建索引 */
const mapNameFromSlug = (s) => {
  const m = String(s || '').match(/^\d+-([a-zA-Z0-9_]+?)-\d+$/);
  return m ? m[1] : null;
};
for (const f of fs.readdirSync(RESEARCH_DIR)) {
  if (!f.endsWith('.json') || f === 'priority.json') continue;
  try {
    const j = readJson(path.join(RESEARCH_DIR, f));
    const base = f.replace(/\.json$/, '');
    researchFiles.set(base, j);
    if (j.slug) {
      researchFiles.set(j.slug, j);
      const fromSlug = mapNameFromSlug(j.slug);
      if (fromSlug && !researchFiles.has(fromSlug)) researchFiles.set(fromSlug, j);
    }
  } catch (e) {
    console.warn(`  ! 忽略无法解析的 research 文件 ${f}: ${e.message}`);
  }
}

const existing = new Map(fs.readdirSync(MAPS_DIR).filter((f) => f.endsWith('.mdx')).map((f) => [f.replace(/\.mdx$/, ''), fs.readFileSync(path.join(MAPS_DIR, f), 'utf8')]));

/* 收集标签写法：手写条目的写法优先当作规范写法 */
const parseFmTags = (text) => {
  const m = text.match(/^tags:\s*\[(.*?)\]/m);
  if (!m) return [];
  return m[1].split(',').map((x) => x.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
};
for (const [, text] of existing) if (!text.includes(MARK)) for (const t of parseFmTags(text)) noteTag(t, true);
for (const [, j] of researchFiles) for (const t of j.tags || []) noteTag(t, false);
const variantReport = [...tagVariants.entries()].filter(([, v]) => v.size > 1);
if (variantReport.length) {
  console.log('标签大小写归一：');
  for (const [key, v] of variantReport) {
    const list = [...v.entries()].sort(
      (a, b) =>
        Number(b[1].curated) - Number(a[1].curated) ||
        b[1].count - a[1].count ||
        (/^[A-Z0-9]{2,}/.test(a[0]) ? 1 : 0) - (/^[A-Z0-9]{2,}/.test(b[0]) ? 1 : 0)
    );
    console.log(`  ${list.map(([t, c]) => `${t}(${c.count}${c.curated ? ',手写' : ''})`).join(' / ')}  →  ${list[0][0]}`);
  }
}

let created = 0, updated = 0, skipped = 0, enriched = 0;
const usedSlugs = new Set(existing.keys());
const stageFix = [];

for (const rec of zeMaps) {
  if (curatedMaps.has(rec.m)) { skipped++; continue; }           // 手写条目已覆盖这张图
  let slug = rec.m;
  const prev = existing.get(slug);
  const isOurs = prev ? prev.includes(MARK) : false;
  if (prev && !isOurs) { skipped++; continue; }                 // 手写条目，保持不动
  if (!prev && usedSlugs.has(slug)) slug = `${rec.m}-${rec.f}`; // 同名不同版本，用工坊 ID 区分

  const research = researchFiles.get(rec.m) || researchFiles.get(rec.s) || null;
  const stageInfo = stageCountFromEntities(rec.s, rec.st || 0);
  if (stageInfo.from) {
    stageFix.push(`${rec.m}: ${rec.st || 0} → ${stageInfo.stages}（${stageInfo.from}）`);
  }
  const mdx = renderEntry({ ...rec, m: rec.m, st: stageInfo.stages }, research, loadWorkshop(rec.f), loadGfl(rec.m));
  if (research?.summary) enriched++;

  if (DRY) { created++; continue; }
  const file = path.join(MAPS_DIR, `${slug}.mdx`);
  if (prev) updated++; else created++;
  fs.writeFileSync(file, mdx);
  usedSlugs.add(slug);
}

console.log(`ZE 地图 ${zeMaps.length} 张`);
console.log(`  ${DRY ? '将生成' : '新建'} ${created} · ${DRY ? '将更新' : '更新'} ${updated} · 跳过手写条目 ${skipped}`);
console.log(`  其中带线上检索资料：${enriched} 张`);
if (stageFix.length) {
  console.log(`  关卡数按实体命名修正 ${stageFix.length} 张：`);
  for (const s of stageFix.slice(0, 25)) console.log(`    ${s}`);
}
if (!DRY) console.log(`  目录：${path.relative(ROOT, MAPS_DIR)}`);
